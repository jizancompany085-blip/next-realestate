export function t(locale: Locale, key: keyof typeof translations['en']): string {
  return translations[locale]?.[key] || translations['en'][key] || key;
}

export function formatPrice(price: number, locale: Locale, purpose: 'Sale' | 'Rent'): string {
  const formatted = price.toLocaleString(locale === 'ar' ? 'ar-SA' : 'en-US');
  const currency = t(locale, 'sar');
  const period = purpose === 'Rent' ? t(locale, 'perYear') : '';
  return `${formatted} ${currency} ${period}`;
}

export function formatArea(area: number, locale: Locale): string {
  const formatted = area.toLocaleString(locale === 'ar' ? 'ar-SA' : 'en-US');
  return `${formatted} ${t(locale, 'sqm')}`;
}

export function formatPropertyType(type: string, locale: Locale): string {
  if (!type) return '';
  const key = type.toLowerCase().trim();
  const map: Record<string, { en: string; ar: string }> = {
    apartment: { en: 'Apartment', ar: 'شقة' },
    villa: { en: 'Villa', ar: 'فيلا' },
    house: { en: 'House', ar: 'منزل' },
    land: { en: 'Land', ar: 'أرض' },
    commercial: { en: 'Commercial', ar: 'تجاري' },
    office: { en: 'Office', ar: 'مكتب' },
    shop: { en: 'Shop', ar: 'محل' },
  };
  return map[key]?.[locale] || type;
}
